const COSMETIC_DEFAULTS = { theme:'theme-default', cardStyle:'cardStyle-default', progressFrame:'progressFrame-default', title:'title-default' } as const;
export type VisualCosmeticType = keyof typeof COSMETIC_DEFAULTS;
export function cosmeticVisualToken(type: VisualCosmeticType, id: string): string {
  const seasonal: Partial<Record<VisualCosmeticType,string>> = { theme:'season-legendary', cardStyle:'season-epic-2', progressFrame:'season-epic-1', title:'season-rare' };
  if (id === COSMETIC_DEFAULTS[type] || id === seasonal[type]) return id;
  const pattern = new RegExp(`^${type}-(?:[1-9])$`);
  return pattern.test(id) ? id : COSMETIC_DEFAULTS[type];
}

